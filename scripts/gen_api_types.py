def ts_type(ann, dto_names: set[str]) -> str:
    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if ann is type(None):
        return "null"
    if origin is typing.Union or origin is getattr(_types, "UnionType", None):
        return " | ".join(ts_type(a, dto_names) for a in args)
    if origin in (list, typing.List):
        return f"{ts_type(args[0], dto_names)}[]" if args else "unknown[]"
    if origin in (dict, typing.Dict):
        if args:
            return f"Record<string, {ts_type(args[1], dto_names)}>"
        return "Record<string, unknown>"
    if origin is typing.Literal:
        return " | ".join(json_repr(a) for a in args)
    if isinstance(ann, type):
        if issubclass(ann, D.Strict) or ann.__name__ in dto_names:
            return ann.__name__
        if ann is str:
            return "string"
        if ann is bool:
            return "boolean"
        if ann in (int, float):
            return "number"
        if ann is Any or ann is object:
            return "unknown"
    return "unknown"


def json_repr(v) -> str:
    import json as _j
    return _j.dumps(v)


def emit_interface(cls) -> str:
    lines = [f"export interface {cls.__name__} {{"]
    for name, field in cls.model_fields.items():
        t = ts_type(field.annotation, set(DTO_ORDER))
        opt = "?" if not field.is_required() else ""
        lines.append(f"  {name}{opt}: {t};")
    lines.append("}")
    return "\n".join(lines)


DTO_ORDER: list[str] = []


def collect() -> list[type]:
    seen: dict[str, type] = {}
    order: list[type] = []

    def visit(cls) -> None:
        if cls.__name__ in seen:
            return
        for f in cls.model_fields.values():
            for sub in _dto_refs(f.annotation):
                visit(sub)
        seen[cls.__name__] = cls
        order.append(cls)

    for name in dir(D):
        obj = getattr(D, name)
        if isinstance(obj, type) and issubclass(obj, D.Strict) and obj is not D.Strict:
            if name not in seen:
                visit(obj)
    return order


def _dto_refs(ann):
    refs = []
    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if origin in (list, typing.List) and args:
        refs.extend(_dto_refs(args[0]))
    elif origin is typing.Union or origin is getattr(_types, "UnionType", None):
        for a in args:
            refs.extend(_dto_refs(a))
    elif isinstance(ann, type) and issubclass(ann, D.Strict) and ann is not D.Strict:
        refs.append(ann)
    return refs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(REPO / "web" / "src" / "api-types.ts"))
    args = ap.parse_args()
    order = collect()
    global DTO_ORDER
    DTO_ORDER = [c.__name__ for c in order]
    parts = [HEADER]
    for cls in order:
        parts.append(emit_interface(cls))
    parts.append(EXTRA.strip() + "\n")
    ep = ["export interface ApiEndpoints {"]
    for method, path, params, body, result in ENDPOINTS:
        key = f'"{method} {path}"'
        p = params
        b = body if body else "never"
        ep.append(f"  {key}: {{ params: {p}; body: {b}; result: {result} }};")
    ep.append("}")
    parts.append("\n".join(ep) + "\n")
    text = "\n\n".join(parts)
    out = Path(args.out)
    if args.check:
        if not out.is_file() or out.read_text() != text:
            print(f"STALE: {out} differs from generated output; run scripts/gen_api_types.py")
            return 1
        print(f"fresh: {out}")
        return 0
    out.write_text(text)
    print(f"wrote {out} ({len(order)} DTOs, {len(ENDPOINTS)} endpoints)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
