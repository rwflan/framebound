"""Training-data export. The framework is designed to make itself obsolete:
every checked frame, mask, metric, and human decision leaves as training
data in formats existing pipelines already consume.

Outputs:
  coco/annotations.json   COCO images/annotations (bbox, RLE segmentation)
  hf/                     Hugging Face imagefolder layout + dataset card
  preferences.jsonl       chosen/rejected pairs per failed slot (DPO-style)
  temporal.jsonl          clip sequences with holds and per-frame metrics
"""
import json
import shutil
from pathlib import Path
from .audit import load_contract, audit
from .pngcodec import read_png


def _rle(mask, w, h):
    """COCO uncompressed RLE over a column-major binary mask."""
    counts, prev, run = [], 0, 0
    for x in range(w):
        for y in range(h):
            v = mask[y * w + x]
            if v == prev:
                run += 1
            else:
                counts.append(run); prev, run = v, 1
    counts.append(run)
    return {"counts": counts, "size": [h, w]}


def _mask_bbox(data, w, h):
    xs, ys, mask = [], [], bytearray(w * h)
    for y in range(h):
        for x in range(w):
            if data[(y * w + x) * 4 + 3] >= 128:
                xs.append(x); ys.append(y); mask[y * w + x] = 1
    if not xs:
        return None, mask, 0
    bbox = [min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1]
    return bbox, mask, len(xs)


def export_dataset(contract_path, out_dir, decisions=None):
    contract_path = Path(contract_path).resolve()
    base = contract_path.parent
    contract = load_contract(contract_path)
    report = audit(contract_path)
    out = Path(out_dir); (out / "coco").mkdir(parents=True, exist_ok=True)
    (out / "hf" / "data").mkdir(parents=True, exist_ok=True)
    w, h = contract["canvas"]
    images, annotations, meta_lines = [], [], []
    ann_id = 0
    error_slots = {e.get("slot"): e["code"] for e in report["errors"] if e.get("slot") is not None}
    frame_metrics = {f["slot"]: f for f in report["metrics"].get("frames", [])}
    for i, rel in enumerate(contract["frames"]):
        src = base / rel
        name = f"{contract['character']}_{contract.get('clip', 'clip')}_{i:04d}.png"
        shutil.copyfile(src, out / "hf" / "data" / name)
        fw, fh, data = read_png(src)
        bbox, mask, area = _mask_bbox(data, fw, fh)
        images.append({"id": i + 1, "file_name": name, "width": fw, "height": fh})
        if bbox:
            ann_id += 1
            annotations.append({"id": ann_id, "image_id": i + 1, "category_id": 1,
                                "bbox": bbox, "area": area, "iscrowd": 0,
                                "segmentation": _rle(mask, fw, fh)})
        decision = (decisions or {}).get(i, {})
        meta_lines.append({"file_name": f"data/{name}", "character": contract["character"],
                           "clip": contract.get("clip", "clip"), "slot": i,
                           "hold_ticks": (contract.get("holds") or [None] * len(contract["frames"]))[i],
                           "technical_status": "fail" if i in error_slots else "pass",
                           "issue_code": error_slots.get(i),
                           "human_decision": decision.get("decision"),
                           "metrics": frame_metrics.get(i, {})})
    coco = {"images": images, "annotations": annotations,
            "categories": [{"id": 1, "name": contract["character"]}]}
    (out / "coco" / "annotations.json").write_text(json.dumps(coco) + "\n", encoding="utf-8")
    (out / "hf" / "metadata.jsonl").write_text(
        "".join(json.dumps(m) + "\n" for m in meta_lines), encoding="utf-8")
    prefs = []
    refs = contract.get("references", [])
    for slot, code in sorted(error_slots.items()):
        if slot < len(refs):
            prefs.append({"slot": slot, "issue_code": code,
                          "prompt": f"Draw frame {slot} of {contract.get('clip', 'clip')} for {contract['character']} within the frozen contract bounds.",
                          "chosen": refs[slot]["file"], "rejected": contract["frames"][slot],
                          "reason": code})
    (out / "preferences.jsonl").write_text("".join(json.dumps(p) + "\n" for p in prefs), encoding="utf-8")
    temporal = {"character": contract["character"], "clip": contract.get("clip", "clip"),
                "loop": contract.get("loop", True), "holds": contract.get("holds"),
                "frames": contract["frames"], "metrics": report["metrics"]}
    (out / "temporal.jsonl").write_text(json.dumps(temporal) + "\n", encoding="utf-8")
    (out / "hf" / "README.md").write_text(
        f"# {contract['character']} animation consistency dataset\n\n"
        "Generated by Framebound from a checked animation project. Each image carries its\n"
        "slot, hold, technical status, issue code, metrics, and human decision. COCO\n"
        "annotations (bbox + RLE segmentation) are in `../coco/annotations.json`;\n"
        "chosen/rejected repair pairs are in `../preferences.jsonl`; clip timing is in\n"
        "`../temporal.jsonl`. Provenance hashes for every source frame are in the audit\n"
        "report produced alongside this export. Licence: as declared by the project owner.\n",
        encoding="utf-8")
    return {"images": len(images), "annotations": len(annotations),
            "preferences": len(prefs), "out": str(out)}
