"""Explicit frame/sheet imports with native timing and per-source receipts."""
import hashlib
import json
from pathlib import Path

from PIL import Image

from ...v2 import storage as S
from ...v2.services.assets import import_asset
from ...v2.services.projects import create_project
from ...v2.services.provenance import write_derived
from ..evaluate import digest
from ..services import loop, tasks


def import_manifest(manifest_path, project, *, review_path=None, native_size=256):
    from ..corpus import _path, _write
    from ...v2.services.errors import InvalidInput
    path = Path(manifest_path).resolve(); root = path.parent
    manifest = json.loads(path.read_text())
    if type(native_size) is not int or not 16 <= native_size <= 512:
        raise InvalidInput('native size must be between 16 and 512')
    cases = manifest['cases']
    if not 1 <= len(cases) <= 800 or len({c['id'] for c in cases}) != len(cases):
        raise InvalidInput('1–800 unique cases required')
    registry = {}; imported = []
    reviews = {c['id']:c for c in json.loads(Path(review_path).read_text())['cases']} if review_path else {}
    create_project(project, {'id':'muse-sequences','name':'Muse original timed sequences'})
    for case in cases:
        import re
        if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9._-]{0,63}',case['id']):
            raise InvalidInput('safe immutable case ID required')
        family = case['family']; split = case['split']
        if split not in {'train','validation','test','development','held_out'}:
            raise InvalidInput('unknown split')
        for identity in [family,*case.get('ancestry',[])]:
            if identity in registry and registry[identity] != split:
                raise InvalidInput('family/reference ancestry crosses splits')
            registry[identity] = split
        holds = case['holds']; descriptors = case['frames']
        if not 1 <= len(holds) <= 24 or len(holds) != len(descriptors) or any(type(h) is not int or h<=0 for h in holds) or sum(holds)>2880:
            raise InvalidInput('explicit frames must match positive authored holds')
        if type(case.get('loop')) is not bool:
            raise InvalidInput('explicit loop flag required')
        if len({d['source_file'] for d in descriptors}) > 4:
            raise InvalidInput('maximum four source images per attempt')
        prefix = 'sequence-'+digest(case['id'])[:18]
        frames = []; events = {}; sources = {}; assets = {}; artifacts = {}
        anchor_set = None
        for slot,d in enumerate(descriptors):
            source = _path(root,d['source_file']); receipt_path = _path(root,d['receipt_file'])
            raw = source.read_bytes(); sha = S.store_blob(project,raw)
            receipt = json.loads(receipt_path.read_text()); receipt_sha = S.store_blob(project,receipt_path.read_bytes())
            if receipt.get('status') != 'completed' or receipt.get('output_sha256') != sha or not receipt.get('model_requested','').startswith('muse-image-'):
                raise InvalidInput('actual successful Muse receipt required')
            if receipt.get('model_observed') not in (None,receipt['model_requested']):
                # The observed identity is preserved, including a provider substitution.
                pass
            conditioning = []; current_anchors = set()
            for n,ref in enumerate(receipt.get('conditioning_ordered',[])):
                ref_path = _path(root,ref['source_file']); ref_sha = S.store_blob(project,ref_path.read_bytes())
                if ref_sha != ref['sha256']:
                    raise InvalidInput('conditioning hash differs')
                evidence_path = ref_path.with_suffix('.receipt.json')
                evidence = json.loads(evidence_path.read_text()) if evidence_path.is_file() else {}
                if evidence.get('status') != 'completed' or evidence.get('output_sha256') != ref_sha:
                    raise InvalidInput('original conditioning receipt unavailable')
                S.store_blob(project,evidence_path.read_bytes())
                aid = prefix+'-ref-'+ref_sha[:16]
                import_asset(project,str(ref_path),aid,source_kind='generated',rights='original')
                role = ref.get('kind','identity')
                conditioning.append(dict(asset_id=aid,byte_sha256=ref_sha,role=role,conditioning_eligibility='original',eligibility_basis='Original generated bytes and matching receipt'))
                if role not in {'boundary','boundary_pose'}: current_anchors.add(ref_sha)
            if sha not in sources:
                if sources:
                    if not anchor_set or not anchor_set.intersection(current_anchors):
                        raise InvalidInput('multi-sheet continuation must retain an original anchor')
                    previous = descriptors[slot-1]
                    previous_source = S.sha256_bytes(_path(root,previous['source_file']).read_bytes())
                    if not any(ref['role'] in {'boundary','boundary_pose'} and ref['byte_sha256'] in {previous_source} for ref in conditioning):
                        # A standalone boundary pose is allowed when declared by exact hash.
                        if not d.get('boundary_pose_sha256') or not any(ref['role'] in {'boundary','boundary_pose'} and ref['byte_sha256']==d['boundary_pose_sha256'] for ref in conditioning):
                            raise InvalidInput('multi-sheet continuation needs a supplied boundary pose')
                source_id = prefix+'-source-'+sha[:16]
                import_asset(project,str(source),source_id,source_kind='generated',rights='original')
                sources[sha] = source_id
                if anchor_set is None: anchor_set = current_anchors
            with Image.open(source) as image:
                image.load()
                if image.width*image.height > 16777216:
                    raise InvalidInput('source pixel ceiling')
                box = d.get('crop',[0,0,image.width,image.height])
                if len(box)!=4 or any(type(v) is not int for v in box) or not 0<=box[0]<box[2]<=image.width or not 0<=box[1]<box[3]<=image.height:
                    raise InvalidInput('invalid native frame crop')
                frame = image.crop(tuple(box)).convert('RGBA').resize((native_size,native_size),Image.Resampling.LANCZOS)
            aid = prefix+f'-frame-{slot}'
            derived = write_derived(project,aid,frame,[sources[sha]]+[r['asset_id'] for r in conditioning],
                dict(operator='explicit-sequence-crop-resize-v1',crop=box,canvas=[native_size,native_size],resampling='LANCZOS'))
            frames.append(aid)
            event = events.setdefault(sha,dict(id=prefix+'-generation-'+sha[:16],provider='meta',requested_model=receipt['model_requested'],
                observed_model=receipt.get('model_observed'),observed_version=receipt.get('version_observed'),evidence_source='external_assertion',outcome='succeeded',
                response_id=receipt.get('response_id'),prompt_sha256=receipt['prompt_sha256'],conditioning=conditioning,original_output_sha256=[sha],
                receipt_sha256=[receipt_sha],output_asset_ids=[],transformations=[]))
            event['output_asset_ids'].append(aid)
            event['transformations'].append(dict(operation='declared crop and LANCZOS resize',input_sha256=sha,output_sha256=derived.byte_sha256))
            relative=f"native/{case['id']}/frame-{slot}.png"
            _write(root/relative,S.blob_path(project,derived.byte_sha256).read_bytes())
            assets[aid]=relative
        metadata = dict(provenance=dict(schema_version='1.0',generations=list(events.values())),
                        sequence_import=dict(schema_version='2.0',family=family,split=split,
                            boundaries=[i for i in range(1,len(descriptors)) if descriptors[i]['source_file']!=descriptors[i-1]['source_file']],
                            continuity='requires temporal assessment; a supplied boundary is not proof of continuity'))
        if case['id'] in reviews: metadata['model_review']=reviews[case['id']]
        spec = dict(id=prefix+'-task',project_id='muse-sequences',animation_id=case['id'],intent=case['intent'],
            subjects='Original Muse sequence; frozen manifest supplies entity graph',canvas=dict(width=native_size,height=native_size),
            timing=dict(holds=holds,ticks_per_second=case.get('ticks_per_second',12)),loop=case['loop'],limits=dict(max_submissions=3),
            requirements=[dict(id='quality',check='animation_quality',required=False,desired_outcome='Assess semantic and temporal correctness separately')])
        tasks.create(project,spec); run_id=prefix+'-run';loop.start(project,spec['id'],run_id)
        feedback=loop.submit(project,run_id,prefix+'-base',frames,generation_metadata=metadata)
        imported.append(dict(id=case['id'],run_id=run_id,revision_id=prefix+'-base',frames=frames,
            technical_status=feedback['technical_status'],coverage=feedback['coverage']))
    return dict(imported=imported,pending=[],project=str(Path(project).resolve()),schema_version='2.0')
